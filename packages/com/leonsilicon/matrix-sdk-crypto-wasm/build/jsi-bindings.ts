// Generates the C++ that connects the wasm2c module to JavaScript through JSI:
//
// - one thunk per export, which the bridge installs as a host function on the exports object
//   the wasm-bindgen glue receives through `__wbg_set_wasm`;
// - one `extern "C"` definition per import, which wasm2c's code calls and which forwards the
//   call to the glue's JavaScript function of the same name.
//
// Values cross the boundary exactly as they would between JavaScript and a real WebAssembly
// instance (ToJSValue / ToWebAssemblyValue): i32 as signed numbers, i64 as BigInt, f32/f64 as
// numbers. The runtime half of the bridge (traps, memory, conversions) is hand-written in
// cpp/Wasm2cBridge.{h,cpp} of the npm package.

import type { Wasm2cFunction, Wasm2cInterface, WasmValueType } from "#wasm2c-header";

export interface JsiBindingsOptions {
  /** The wasm2c module name (`-n`), e.g. `mxcrypto`. */
  moduleName: string;
  /** The header wasm2c wrote, relative to the generated C++ file. */
  headerName: string;
  /** A line naming what the bindings were generated from, for the file header. */
  provenance: string;
}

const CONVERT_ARG: Record<WasmValueType, string> = {
  u32: "argToU32",
  u64: "argToU64",
  f32: "argToF32",
  f64: "argToF64",
};

const CONVERT_RESULT: Record<WasmValueType, string> = {
  u32: "jsToU32",
  u64: "jsToU64",
  f32: "jsToF32",
  f64: "jsToF64",
};

function cString(value: string): string {
  return JSON.stringify(value); // JSON escapes are valid C escapes for these ASCII names
}

function exportThunk(fn: Wasm2cFunction, index: number): string {
  const lines: string[] = [];
  const argsParams =
    fn.params.length > 0 ? "const jsi::Value* args, size_t count" : "const jsi::Value*, size_t";
  lines.push(`jsi::Value export_${index}(Bridge& bridge, jsi::Runtime& rt, ${argsParams}) {`);
  fn.params.forEach((type, param) => {
    lines.push(`  const ${type} p${param} = ${CONVERT_ARG[type]}(rt, args, count, ${param});`);
  });
  const call = `${fn.symbol}(&bridge.instance()->module${fn.params.map((_, param) => `, p${param}`).join("")})`;
  if (fn.result === "void") {
    lines.push(`  bridge.invoke(rt, [&] { ${call}; });`);
    lines.push("  return jsi::Value::undefined();");
  } else {
    lines.push(`  ${fn.result} result = 0;`);
    lines.push(`  bridge.invoke(rt, [&] { result = ${call}; });`);
    lines.push("  return wasmToJs(rt, result);");
  }
  lines.push("}");
  return lines.join("\n");
}

function importDefinition(fn: Wasm2cFunction, index: number, importStruct: string): string {
  const params = fn.params.map((type, param) => `, ${type} p${param}`).join("");
  const lines: string[] = [];
  lines.push(`${fn.result} ${fn.symbol}(${importStruct}* context${params}) {`);
  lines.push("  Bridge& bridge = *context->bridge;");
  lines.push("  jsi::Runtime& rt = bridge.runtime();");
  let call: string;
  if (fn.params.length === 0) {
    call = `bridge.callImport(${index}, nullptr, 0)`;
  } else {
    lines.push(
      `  const jsi::Value args[] = {${fn.params.map((_, param) => `wasmToJs(rt, p${param})`).join(", ")}};`,
    );
    call = `bridge.callImport(${index}, args, ${fn.params.length})`;
  }
  if (fn.result === "void") {
    lines.push(`  ${call};`);
  } else {
    lines.push(`  return ${CONVERT_RESULT[fn.result]}(rt, ${call});`);
  }
  lines.push("}");
  return lines.join("\n");
}

export function generateJsiBindings(iface: Wasm2cInterface, options: JsiBindingsOptions): string {
  const { moduleName, headerName, provenance } = options;
  const out: string[] = [];
  out.push(
    `// Generated by @-/com.leonsilicon.matrix-sdk-crypto-wasm.build (jsi-bindings.ts). Do not edit.`,
    `// ${provenance}`,
    `// ${iface.exports.length} exports, ${iface.imports.length} imports.`,
    "",
    `#include "Wasm2cBridge.h"`,
    `#include "${headerName}"`,
    "",
    "namespace jsi = facebook::jsi;",
    "using namespace matrixsdkcryptowasm;",
    "",
    "// wasm2c leaves the import struct to the embedder: it is the `context` every import receives.",
    `${iface.importStruct} {`,
    "  Bridge* bridge;",
    "};",
    "",
    "namespace matrixsdkcryptowasm::generated {",
    "",
    "struct Instance {",
    `  ${iface.instanceType} module;`,
    `  ${iface.importStruct} imports;`,
    "};",
    "",
    "Instance* instantiate(Bridge& bridge) {",
    "  auto* instance = new Instance();",
    "  instance->imports.bridge = &bridge;",
    `  wasm2c_${moduleName}_instantiate(&instance->module, &instance->imports);`,
    "  return instance;",
    "}",
    "",
    "void destroy(Instance* instance) {",
    `  wasm2c_${moduleName}_free(&instance->module);`,
    "  delete instance;",
    "}",
    "",
    "wasm_rt_memory_t* memory(Instance* instance) {",
    `  return ${iface.memorySymbol}(&instance->module);`,
    "}",
    "",
    `const char* const kImportModule = ${cString(iface.importModule)};`,
    `const size_t kImportCount = ${iface.imports.length};`,
    "const char* const kImportNames[] = {",
    ...iface.imports.map((fn) => `  ${cString(fn.name)},`),
    "};",
    "",
    "namespace {",
    "",
    ...iface.exports.map((fn, index) => exportThunk(fn, index) + "\n"),
    "} // namespace",
    "",
    `const size_t kExportCount = ${iface.exports.length};`,
    "const ExportEntry kExports[] = {",
    ...iface.exports.map(
      (fn, index) => `  {${cString(fn.name)}, ${fn.params.length}, &export_${index}},`,
    ),
    "};",
    "",
    "} // namespace matrixsdkcryptowasm::generated",
    "",
    "using namespace matrixsdkcryptowasm::generated;",
    "",
    'extern "C" {',
    "",
    ...iface.imports.map((fn, index) => importDefinition(fn, index, iface.importStruct) + "\n"),
    '} // extern "C"',
    "",
  );
  return out.join("\n");
}
